import Foundation
import TOMLKit

/// Renders, writes and validates the Switchyard deployment file this app owns.
///
/// The app regenerates the whole file on every apply, so rendering is a plain
/// template rather than a TOML document merge (design.md decision 4).
package enum SwitchyardConfigWriter {
    package enum Failure: LocalizedError, Equatable {
        case invalidProfile([String])
        case binaryNotExecutable(String)
        case validationFailed(String)
        case launchFailed(String)

        package var errorDescription: String? {
            switch self {
            case .invalidProfile(let reasons):
                "The routing setup is incomplete: " + reasons.joined(separator: " ")
            case .binaryNotExecutable(let path):
                "switchyard-server is not executable at \(path)."
            case .validationFailed(let output):
                "switchyard-server rejected the generated config:\n\(output)"
            case .launchFailed(let reason):
                "Could not run switchyard-server: \(reason)"
            }
        }
    }

    /// Name of the generated `[llm_clients.<name>]` entry the judge uses when it
    /// cannot share the route's own client.
    package static let judgeClientName = "judge_litellm"

    /// Directory this app owns. Never inside the Switchyard repo checkout,
    /// and never the real one while a test process is running.
    package static var supportDirectory: URL { UserDataLocations.supportDirectory }

    package static var defaultConfigURL: URL {
        supportDirectory.appendingPathComponent("routes.toml")
    }

    // MARK: - Render

    /// The complete `routes.toml` for a profile.
    ///
    /// The explicit algorithm selection determines the rendered route shape.
    /// - Parameter serverSupportsVision: whether the resolved `switchyard-server`
    ///   understands the route's `vision` key. Older builds reject the whole
    ///   file when it appears, so an undetected server gets a text-only route.
    package static func render(profile: RoutingProfile, serverSupportsVision: Bool = false) throws -> String {
        guard profile.isValid else {
            throw Failure.invalidProfile(profile.validationErrors)
        }
        guard profile.algorithm != nil else {
            throw Failure.invalidProfile(["Choose a routing algorithm."])
        }
        let client = profile.provider.clientName

        var toml = """
            # Generated by switchyard-desktop. Edits are overwritten on the next Apply.
            schema_version = 1

            # Loopback proxies manage their own authentication and receive no caller credential.
            # Direct remote upstreams receive the caller credential; no key is stored here.
            [llm_clients.\(client)]
            format = \(tomlQuoted(profile.provider.wireFormat))
            base_url = \(tomlQuoted(profile.upstreamBaseURL))
            forward_auth = \(profile.forwardsCallerCredential ? "true" : "false")

            """

        if let judge = profile.judgeTargetName, let judgeModel = profile.judgeModelName {
            if profile.routesJudgeThroughLiteLLM {
                toml += """

                    [llm_clients.\(judgeClientName)]
                    format = \(tomlQuoted(profile.provider.wireFormat))
                    base_url = \(tomlQuoted(LiteLLMProcessManager.upstream))
                    forward_auth = false

                    """
            }
            toml += """

                [targets.\(judge)]
                id = \(tomlQuoted(judgeModel))
                llm_client = \(tomlQuoted(profile.routesJudgeThroughLiteLLM ? judgeClientName : client))

                """
            toml += judgeReasoningEffort(profile: profile)
            if let options = profile.judgeNativeOptions { toml += options + "\n" }
        }

        if profile.allTargets.isEmpty { toml += "\n[targets]\n" }
        for (tier, name) in zip(profile.allTargets, profile.allTargetNames) {
            toml += """

                [targets.\(name)]
                id = \(tomlQuoted(tier.assignedModel ?? ""))
                llm_client = \(tomlQuoted(client))

                """
            toml += reasoningEffort(for: tier, in: profile)
            toml += systemPrompt(for: tier, in: profile)
            if let options = tier.nativeOptions { toml += options + "\n" }
        }

        // Native options replace the whole algorithm body. In particular, no
        // app defaults are merged over a user's prompt, trigger or model groups.
        toml += "\n[routes.main]\nid = \(tomlQuoted(profile.routeID))\n"
        toml += contextWindow(profile: profile)
        if let options = profile.nativeRouteOptions {
            toml += options + "\n"
        } else {
            toml += "tool_calling = true\nreasoning = true\n"
            toml += imageInput(profile: profile, serverSupportsVision: serverSupportsVision)
            toml += defaultRouteOptions(profile: profile)
        }

        return toml
    }

    // MARK: - Route rendering

    /// Required native fields and the documented starting presets. Optional
    /// settings and built-in prompts remain owned by the server snapshot.
    package static func defaultRouteOptions(profile: RoutingProfile) -> String {
        guard let algorithm = profile.algorithm else { return "" }
        let names = profile.targetNames
        let efficient = names.first ?? "efficient"
        let capable = names.last ?? "capable"
        let judge = profile.judgeTargetName ?? profile.judgeSharedTargetName
            ?? profile.classifierTargetName ?? efficient
        let trigger = "classify_trigger = \(tomlQuoted(profile.classifyTrigger.rawValue))\n"
        let tiers = "capable_target = \(tomlQuoted(capable))\nefficient_target = \(tomlQuoted(efficient))\n"
        switch algorithm {
        case .auto:
            return "type = \"auto\"\n" + tiers
        case .planExecute:
            return "type = \"plan_execute\"\n" + tiers
        case .stageRouter:
            return "type = \"stage_router\"\n" + tiers
                + "picker = \"efficient_first\"\nconfidence_threshold = 0.5\nrecent_turn_window = 3\n"
        case .capability:
            return "type = \"llm_classifier\"\nmode = \"capability\"\n"
                + "classifier_target = \(tomlQuoted(judge))\nstrong_target = \(tomlQuoted(capable))\nweak_target = \(tomlQuoted(efficient))\n"
                + "base_threshold = 0.5\n" + trigger
        case .escalation:
            return "type = \"llm_classifier\"\nmode = \"escalation\"\n"
                + "classifier_target = \(tomlQuoted(judge))\nstrong_target = \(tomlQuoted(capable))\nweak_target = \(tomlQuoted(efficient))\n"
                + "escalation = {}\n"
        case .composite:
            return "type = \"composite\"\n\n[routes.main.classifier]\ntarget = \(tomlQuoted(judge))\nbase_threshold = 0.5\n"
                + trigger + "\n[routes.main.stage]\n" + tiers + "confidence_threshold = 0.5\n"
        case .advisor:
            return "type = \"advisor\"\nexecutor_target = \(tomlQuoted(efficient))\nadvisor_target = \(tomlQuoted(judge))\n"
                + (profile.reviewerSystemPrompt.map { "reviewer_system_prompt = \(tomlQuoted($0))\n" } ?? "")
        case .random:
            return "type = \"random\"\ntargets = [\(names.map(tomlQuoted).joined(separator: ", "))]\n"
        case .passthrough:
            return "type = \"passthrough\"\ntarget = \(tomlQuoted(efficient))\n"
        case .noop:
            return "type = \"noop\"\n"
        case .prefillRouter:
            return "type = \"prefill_router\"\ntargets = [\(names.map(tomlQuoted).joined(separator: ", "))]\ncheckpoint = \"/path/to/router.pt\"\ndevice = \"cpu\"\n"
        case .llmClassifier:
            return classifierRoute(profile: profile, names: names)
        }
    }

    /// What the route tells Codex the conversation window is.
    ///
    /// Switchyard serves this key as both `context_window` and
    /// `max_context_window` on the route's model card, and Codex applies 95% of
    /// it, holding the rest back for the reply. Left out, Codex falls back to
    /// its own 272k default, which is well under what the GPT-5.6 family takes
    /// — so naming the real maximum here is the difference between compacting
    /// at 258k and compacting at 828k.
    ///
    /// Native route options own the whole body, so a window written there wins
    /// rather than colliding with this one.
    private static func contextWindow(profile: RoutingProfile) -> String {
        guard let window = profile.routeContextWindow else { return "" }
        if let native = profile.nativeRouteOptions, mentions("context_window", in: native) { return "" }
        if profile.longContextIsBlocked {
            return """
                # Long context is off in switchyard-desktop's settings: OpenAI bills a prompt over
                # \(RoutingProfile.standardContextWindow) tokens at premium rates, so Codex compacts
                # the conversation before it gets there.
                context_window = \(window)

                """
        }
        let capping = profile.contextWindowCappingModels
        guard !capping.isEmpty else { return "context_window = \(window)\n" }
        let verb = capping.count == 1 ? "takes" : "take"
        return """
            # The largest window every selectable target accepts: \(capping.joined(separator: ", "))
            # \(verb) no more, and Codex measures one window against the whole
            # conversation, whichever target serves a turn.
            context_window = \(window)

            """
    }

    /// `reasoning_effort` for a judge of its own, from the classifier role.
    ///
    /// The judge weighs one short classification per turn, so its effort is
    /// worth setting apart from the models that serve the work. Judge target
    /// options are the user's own words and win, as everywhere else.
    private static func judgeReasoningEffort(profile: RoutingProfile) -> String {
        guard let effort = profile.classifierRole?.effort else { return "" }
        if let options = profile.judgeNativeOptions, mentions("reasoning_effort", in: options) {
            return ""
        }
        return "reasoning_effort = \(tomlQuoted(effort.rawValue))\n"
    }

    /// `reasoning_effort` for a target, from the role it holds.
    ///
    /// Native target settings are the user's own words and win outright: a
    /// profile that already names an effort there is not overruled by a role.
    private static func reasoningEffort(for tier: TaskTier, in profile: RoutingProfile) -> String {
        guard let effort = profile.effort(of: tier) else { return "" }
        if let options = tier.nativeOptions, mentions("reasoning_effort", in: options) { return "" }
        return "reasoning_effort = \(tomlQuoted(effort.rawValue))\n"
    }

    /// `system_prompt` for a target, from the role it holds.
    ///
    /// The role says what the model is told; the judge is told something else
    /// entirely, which is the role's description. Native target settings are
    /// the user's own words and win here too, so a profile that already writes
    /// a prompt into its options keeps it.
    private static func systemPrompt(for tier: TaskTier, in profile: RoutingProfile) -> String {
        guard let prompt = profile.role(of: tier)?.modelPrompt else { return "" }
        if let options = tier.nativeOptions, mentions("system_prompt", in: options) { return "" }
        return "system_prompt = \(tomlQuoted(prompt))\n"
    }

    /// Whether a native body already sets a key itself.
    private static func mentions(_ key: String, in options: String) -> Bool {
        options.split(separator: "\n").contains { line in
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            guard !trimmed.hasPrefix("#") else { return false }
            return trimmed.hasPrefix(key)
        }
    }

    /// Codex reads image support from the route's model card and drops an
    /// attached image before sending when it reads text-only, so this is
    /// declared only when every target the route can select accepts one.
    private static func imageInput(profile: RoutingProfile, serverSupportsVision: Bool) -> String {
        guard profile.advertisesImageInput else {
            // An empty capability set means discovery never reported modalities,
            // so there is nothing to explain — only a known text-only target is
            // worth a note.
            guard !profile.imageCapableModelIDs.isEmpty else { return "" }
            let textOnly = profile.textOnlyAssignedModels
            guard !textOnly.isEmpty else { return "" }
            return """
                # Image input stays undeclared: \(textOnly.joined(separator: ", ")) takes
                # text only, and a route may advertise images only when every target
                # accepts them.

                """
        }
        guard serverSupportsVision else {
            return """
                # Every target accepts images, but this switchyard-server build does not
                # take the route `vision` key, so the route stays text-only. Update
                # switchyard-server to route images.

                """
        }
        return """
            vision = true

            """
    }

    private static func classifierRoute(
        profile: RoutingProfile,
        names: [String]
    ) -> String {
        let list = names.map { "\"\($0)\"" }.joined(separator: ", ")
        guard let classifier = profile.judgeTargetName ?? profile.judgeSharedTargetName
                ?? profile.classifierTargetName,
              let fallback = profile.defaultTargetName else {
            return ""
        }
        // A judge-only target is not a completion destination, so it appears in
        // `models.judge` and nowhere else. A judge sharing a target's model on
        // one client has no target of its own and names that target instead.
        let judge = profile.judgeTargetName ?? classifier

        // One model group per tier: the judge's verdict names a group, and
        // Switchyard serves that group's first model. Every group but `judge`
        // must also appear in `any`, which is the route's fallback order.
        var groups = """

            [routes.main.models]
            # Every selectable target, in last-resort fallback order.
            any = [\(list)]
            \(judgeGroupNote(profile: profile))judge = ["\(judge)"]

            """
        for name in names {
            groups += "\(name) = [\"\(name)\"]\n"
        }

        return """

            type = "llm_classifier"
            mode = "custom"
            default_target = "\(fallback)"
            classify_trigger = "\(profile.classifyTrigger.rawValue)"
            prompt = '''
            \(judgePrompt(profile: profile, names: names))
            '''
            response_schema = '''
            \(responseSchema(names: names))
            '''
            \(groups)
            [routes.main.policy]
            type = "target_selector"
            selector = "/decision/target"

            """
    }

    /// What the `judge` group means when the judge has no target of its own.
    ///
    /// Switchyard keeps one target per model id on a client, so a judge running
    /// a model a target already serves runs as that target — with that target's
    /// settings rather than the classifier role's.
    private static func judgeGroupNote(profile: RoutingProfile) -> String {
        guard profile.judgeModelID != nil, profile.judgeTargetName == nil,
              let shared = profile.judgeSharedTargetName else {
            return "# The judge's own candidates. Never a routing destination.\n"
        }
        return """
            # The judge runs \(shared)'s model on the same client, so Switchyard keeps
            # one target for both and the judge takes that target's settings.

            """
    }

    /// The judge's instructions, built from each tier's own name and description.
    /// The judge's prompt: the classifier role's template with the groups
    /// rendered into it.
    ///
    /// The group list is generated rather than written, because it is the one
    /// part that has to match the targets exactly — a hand-kept list is what
    /// leaves a route naming a target that no longer exists.
    private static func judgePrompt(profile: RoutingProfile, names: [String]) -> String {
        var groups: [String] = []
        for (tier, name) in zip(profile.tiers, names) {
            let label = tomlSafe(tier.displayName)
            let summary = tomlSafe(tier.summary)
            // A slug drops anything non-ASCII, so a tier named in another script
            // would reach the judge as "tier2" with its name lost. Keep the name
            // whenever the slug no longer carries it.
            let carriesName = name == label.lowercased().replacingOccurrences(of: " ", with: "_")
            let described = [carriesName ? nil : label, summary.isEmpty ? nil : summary]
                .compactMap { $0 }
                .joined(separator: " — ")
            groups.append(described.isEmpty ? "- \(name)" : "- \(name): \(described)")
        }
        // The route carries a response schema, but an upstream is free to serve the
        // judge without enforcing it — Codex's own backend does — and a model that
        // never sees the schema answers the request instead of routing it. The
        // contract therefore has to be stated in the prompt as well, which is why
        // the built-in template ends with it.
        let template = tomlSafeBlock(profile.classifierRole?.text ?? RoutingRole.builtInClassifier.text)
        return template
            .replacingOccurrences(
                of: RoutingRole.targetsPlaceholder,
                with: groups.joined(separator: "\n")
            )
            .replacingOccurrences(
                of: RoutingRole.targetNamesPlaceholder,
                with: names.joined(separator: ", ")
            )
    }

    /// The judge's prompt as this profile would write it, groups and all.
    ///
    /// The routing step shows this rather than the classifier role's template:
    /// the one part of the prompt nobody writes is the group list, and it is
    /// the part worth reading before trusting a routing decision.
    package static func judgePromptPreview(profile: RoutingProfile) -> String {
        judgePrompt(profile: profile, names: profile.targetNames)
    }

    private static func responseSchema(names: [String]) -> String {
        let list = names.map { "\"\($0)\"" }.joined(separator: ", ")
        return """
            {
              "type": "object",
              "properties": {
                "decision": {
                  "type": "object",
                  "properties": {
                    "target": {
                      "type": "string",
                      "enum": [\(list)]
                    }
                  },
                  "required": ["target"],
                  "additionalProperties": false
                }
              },
              "required": ["decision"],
              "additionalProperties": false
            }
            """
    }

    /// Tier names and descriptions are free text, and they land inside TOML
    /// multi-line literal strings — which have no escapes, so the one sequence
    /// that could break out has to go.
    private static func tomlSafe(_ text: String) -> String {
        tomlSafeBlock(text)
            .replacingOccurrences(of: "\r", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
    }

    /// The same guard for text whose own line breaks are the point — the judge's
    /// prompt is a template, and flattening it would run its instructions and
    /// its group list into one line.
    private static func tomlSafeBlock(_ text: String) -> String {
        text
            .replacingOccurrences(of: "'''", with: "''")
            .replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Escapes values inserted into TOML basic strings. Role descriptions use
    /// TOML literal strings above, while user-editable route settings use this.
    package static func tomlQuoted(_ text: String) -> String {
        let escaped = text.unicodeScalars.map { scalar -> String in
            switch scalar.value {
            case 0x22: return "\\\""
            case 0x5C: return "\\\\"
            case 0x0A: return "\\n"
            case 0x0D: return "\\r"
            case 0x09: return "\\t"
            case 0...0x1F, 0x7F: return String(format: "\\u%04X", scalar.value)
            default: return String(scalar)
            }
        }.joined()
        return "\"\(escaped)\""
    }

    // MARK: - Write

    /// Writes the rendered config, creating the support directory if needed.
    @discardableResult
    package static func write(
        profile: RoutingProfile,
        to url: URL = SwitchyardConfigWriter.defaultConfigURL,
        serverSupportsVision: Bool = false
    ) throws -> URL {
        let toml = try render(profile: profile, serverSupportsVision: serverSupportsVision)
        try FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(),
            withIntermediateDirectories: true
        )
        try toml.write(to: url, atomically: true, encoding: .utf8)
        return url
    }

    // MARK: - Validate

    /// Runs `switchyard-server --config <path> --dry-run`.
    /// Throws `Failure.validationFailed` with the binary's own output when it rejects the config.
    package static func validate(configPath: URL, binaryPath: URL) throws {
        guard FileManager.default.isExecutableFile(atPath: binaryPath.path) else {
            throw Failure.binaryNotExecutable(binaryPath.path)
        }

        let process = Process()
        process.executableURL = binaryPath
        process.arguments = ["--config", configPath.path, "--dry-run"]
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe

        do {
            try process.run()
        } catch {
            throw Failure.launchFailed(DiagnosticRedactor.redact(error.localizedDescription))
        }

        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()

        guard process.terminationStatus == 0 else {
            let output = DiagnosticRedactor.redact(
                String(decoding: data, as: UTF8.self)
                    .trimmingCharacters(in: .whitespacesAndNewlines)
            )
            throw Failure.validationFailed(
                output.isEmpty ? "exit code \(process.terminationStatus)" : output
            )
        }
    }
}
