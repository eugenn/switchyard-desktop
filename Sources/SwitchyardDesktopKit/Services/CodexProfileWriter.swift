import Foundation
import TOMLKit

/// Generates and removes `$CODEX_HOME/switchyard-desktop.config.toml`, the Codex
/// configuration layer this app owns.
///
/// Codex layers `<name>.config.toml` over the user's own configuration when a
/// session is started as `codex --profile <name>`, so installing a route means
/// adding a file rather than editing one that belongs to the user. Nothing here
/// backs anything up or restores anything: the file is generated whole, and
/// deleting it is the entire undo.
///
/// That is the point of the design. A run that ends without cleanup — a crash, a
/// Force Quit, a log-out this app never sees — leaves the user's `config.toml`
/// byte-for-byte as it was. The only leftover is a file nothing reads unless the
/// user passes the flag, and the next launch removes it.
package enum CodexProfileWriter {
    /// Name of the `[model_providers.<name>]` entry this app owns.
    package static let providerKey = "switchyard-desktop"

    /// Header Switchyard records as each routed turn's `origin`. Switchyard
    /// never infers it from `User-Agent`, so the client has to send it, and
    /// Codex sends whatever `http_headers` lists. An older Switchyard ignores
    /// the header and logs no origin.
    package static let originHeader = "x-switchyard-origin"
    package static let originValue = "codex-cli"

    package enum Failure: LocalizedError, Equatable {
        case invalidProfile([String])
        case renderedInvalidTOML(String)
        case foreignProfileFile(String)

        package var errorDescription: String? {
            switch self {
            case .invalidProfile(let reasons):
                return "The routing setup is incomplete: " + reasons.joined(separator: " ")
            case .renderedInvalidTOML(let detail):
                return "The generated Codex profile did not parse and was not written:\n\(detail)"
            case .foreignProfileFile(let path):
                return """
                    \(path) is no longer the file switchyard-desktop generated, so it was left in \
                    place. Check it and remove it yourself if you do not need it.
                    """
            }
        }
    }

    /// `$CODEX_HOME/switchyard-desktop.config.toml`, defaulting under `~/.codex`.
    package static var defaultProfileURL: URL { CodexLocations.defaultProfileURL }

    // MARK: - Install

    /// Writes the profile layer, replacing any previous generation of it.
    ///
    /// There is no backup and no merge: every byte of this file is this app's,
    /// so the current profile simply replaces the last one.
    @discardableResult
    package static func install(
        profile: RoutingProfile,
        profilePath: URL = CodexProfileWriter.defaultProfileURL
    ) throws -> URL {
        guard profile.isValid else { throw Failure.invalidProfile(profile.validationErrors) }

        let rendered = render(profile: profile)
        let table: TOMLTable
        do {
            table = try TOMLTable(string: rendered)
        } catch {
            throw Failure.renderedInvalidTOML(String(describing: error))
        }
        guard table["model_provider"]?.string == providerKey,
              table["model"]?.string == profile.routeID else {
            throw Failure.renderedInvalidTOML("expected keys are missing after rendering")
        }

        try FileManager.default.createDirectory(
            at: profilePath.deletingLastPathComponent(),
            withIntermediateDirectories: true
        )
        try rendered.write(to: profilePath, atomically: true, encoding: .utf8)
        return profilePath
    }

    /// The generated file. Pure — exposed for tests and for previewing it.
    package static func render(profile: RoutingProfile) -> String {
        var lines = [
            "# Generated by switchyard-desktop. Safe to delete at any time.",
            "#",
            "# Codex reads this file only for sessions started as",
            "# `\(CodexLocations.launchCommand)`. Your own config.toml beside it is",
            "# never modified, and sessions started without the flag are unaffected.",
            "",
        ]
        lines.append(contentsOf: selectionLines(profile: profile))
        return lines.joined(separator: "\n")
    }

    /// A block the user can paste into their own `config.toml` by hand, so
    /// Codex Desktop can use this route too — Desktop has no `--profile` of
    /// its own, so it never sees the generated layer above.
    ///
    /// This app never writes this text anywhere: copying it is the user's own
    /// edit, to their own file, and it makes the route their Codex default
    /// everywhere, not only in Desktop — every session that does not select a
    /// different profile picks it up, `codex --profile switchyard-desktop` included.
    /// Pure, like `render(profile:)`, and exposed for the same reasons.
    package static func manualConfigSnippet(profile: RoutingProfile) -> String {
        var lines = [
            "# Paste into ~/.codex/config.toml to make this route the Codex default",
            "# everywhere, including Codex Desktop. Remove these lines to undo it;",
            "# nothing here is written by switchyard-desktop.",
            "",
        ]
        lines.append(contentsOf: selectionLines(profile: profile))
        return lines.joined(separator: "\n")
    }

    /// The `model`/`model_provider` selection and the provider table, shared by
    /// the generated profile and the manual snippet so the two never drift.
    private static func selectionLines(profile: RoutingProfile) -> [String] {
        var lines = [
            "model = \"\(profile.routeID)\"",
            "model_provider = \"\(providerKey)\"",
        ]
        // Switchyard leaves Codex's catalog intact. Summary preferences belong
        // to the client, and this layer is the only place the app states one.
        if !profile.advertisesReasoningSummaries {
            lines.append("model_reasoning_summary = \"none\"")
        }
        lines.append(contentsOf: [
            "",
            "[model_providers.\(providerKey)]",
            "name = \"switchyard-desktop (Switchyard)\"",
            "base_url = \"\(profile.proxyBaseURL)\"",
            "wire_api = \"\(profile.provider.codexWireAPI)\"",
            "# Keep Codex subscription authentication enabled for this provider.",
            "# The bundled LiteLLM route does not forward this credential upstream;",
            "# a direct upstream override may require it.",
            "requires_openai_auth = true",
            "# Labels this client in Switchyard's routing log, so turns from Codex are",
            "# told apart from anything else pointed at the same proxy.",
            "http_headers = { \"\(originHeader)\" = \"\(originValue)\" }",
            "",
        ])
        return lines
    }

    // MARK: - Remove

    /// Deletes the generated layer. Returns whether a file was actually removed.
    ///
    /// A file that no longer selects this app's provider is left alone: the name
    /// is this app's by convention, not by right, and silently deleting content
    /// someone else put there would be the very thing this design avoids.
    ///
    /// One exception: Codex itself rewrites the active profile file with its own
    /// UI state (`[tui.*]` counters) once the generated layer is gone, or when
    /// the file was missing. That residue routes nothing and holds nothing of the
    /// user's, so it is removed as well; otherwise a Stop after such a rewrite
    /// would fail and leave routing running.
    @discardableResult
    package static func remove(
        profilePath: URL = CodexProfileWriter.defaultProfileURL
    ) throws -> Bool {
        guard FileManager.default.fileExists(atPath: profilePath.path) else { return false }
        guard isRemovable(profilePath: profilePath) else {
            throw Failure.foreignProfileFile(profilePath.path)
        }
        try FileManager.default.removeItem(at: profilePath)
        return true
    }

    /// The generated layer, or a file holding nothing but Codex's own `tui` state.
    private static func isRemovable(profilePath: URL) -> Bool {
        if readSelection(profilePath: profilePath)?.selectsManagedProvider == true { return true }
        guard let text = try? String(contentsOf: profilePath, encoding: .utf8),
              let table = try? TOMLTable(string: text) else {
            return false
        }
        return table.keys.allSatisfy { $0 == "tui" }
    }

    // MARK: - Read

    /// Whether a generated layer selecting this app's provider is on disk.
    package static func isInstalled(profilePath: URL = CodexProfileWriter.defaultProfileURL) -> Bool {
        readSelection(profilePath: profilePath)?.selectsManagedProvider ?? false
    }

    /// The two keys the layer owns, as they currently stand on disk. A missing
    /// or malformed file reads as no selection.
    package static func readSelection(
        profilePath: URL = CodexProfileWriter.defaultProfileURL
    ) -> CodexRouteSelection? {
        guard let text = try? String(contentsOf: profilePath, encoding: .utf8),
              let table = try? TOMLTable(string: text) else {
            return nil
        }
        return CodexRouteSelection(
            model: table["model"]?.string,
            provider: table["model_provider"]?.string
        )
    }
}
